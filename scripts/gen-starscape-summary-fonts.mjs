// Regenerate supabase/functions/starscape-summary/fonts.ts from the TTFs in
// that function's fonts/ dir. base64-embedding keeps the fonts in the JS
// import graph so `supabase functions deploy` bundles them — Deno.readFile of
// static font assets is NOT included by the deploy bundler (it 503'd the
// isolate via an unhandled module-scope rejection).
//
// Run:  node scripts/gen-starscape-summary-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/functions/starscape-summary/fonts/';
const names = ['Orbitron-700', 'Orbitron-500', 'Rajdhani-500', 'Rajdhani-600'];

let out =
  '// AUTO-GENERATED by scripts/gen-starscape-summary-fonts.mjs — do not edit.\n' +
  '// base64 TTFs embedded in the import graph so `supabase functions deploy`\n' +
  '// bundles them (Deno.readFile of static font assets is not deployed).\n\n';

for (const n of names) {
  const b64 = readFileSync(dir + n + '.ttf').toString('base64');
  out += `export const ${n.replace('-', '_')} = "${b64}";\n`;
}

writeFileSync('supabase/functions/starscape-summary/fonts.ts', out);
console.log('regenerated fonts.ts (' + names.length + ' fonts)');
