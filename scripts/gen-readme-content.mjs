// Bundle docs/readme-io/pages/*.md into supabase/functions/readme-sync/content.ts,
// the payload the `readme-sync` edge function pushes to the ReadMe (readme.io)
// v2 API.
//
//   node scripts/gen-readme-content.mjs
//   npm run gen:readme-content
//
// Why a generated .ts instead of reading the .md at runtime: the Supabase
// functions deploy bundler only ships what is reachable through the JS import
// graph — `Deno.readFile` of a static asset is NOT included (same lesson as
// starscape-summary's embedded fonts.ts). So the markdown has to become code.
//
// Source of truth stays the markdown under docs/readme-io/pages/ — authored and
// reviewed in the repo, never edited in the ReadMe web UI (the sync overwrites).
//
// Frontmatter (a deliberately tiny YAML subset — flat `key: value` only):
//   slug      required  ReadMe page slug (stable identity across syncs)
//   title     required  page title
//   category  required  category slug the page belongs to
//   position  optional  sort order within the category (number)
//   excerpt   optional  short summary shown in ReadMe's page list

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PAGES_DIR = path.join(ROOT, 'docs', 'readme-io', 'pages');
const OUT = path.join(ROOT, 'supabase', 'functions', 'readme-sync', 'content.ts');

const REQUIRED = ['slug', 'title', 'category'];

/**
 * Split `---\n<frontmatter>\n---\n<body>` into its two halves.
 * Throws with the file name on a malformed header so a typo fails the
 * generator instead of silently publishing a page with no slug.
 */
function splitFrontmatter(raw, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing or malformed --- frontmatter block`);
  return { head: match[1], body: match[2].trim() };
}

function parseFrontmatter(head, file) {
  const meta = {};
  for (const line of head.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const sep = line.indexOf(':');
    if (sep === -1) throw new Error(`${file}: frontmatter line is not "key: value" → ${line}`);
    const key = line.slice(0, sep).trim();
    let value = line.slice(sep + 1).trim();
    // Strip one layer of matching quotes, if present.
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    meta[key] = value;
  }
  for (const key of REQUIRED) {
    if (!meta[key]) throw new Error(`${file}: frontmatter is missing required key "${key}"`);
  }
  return meta;
}

function main() {
  if (!fs.existsSync(PAGES_DIR)) {
    throw new Error(`pages directory not found: ${PAGES_DIR}`);
  }

  // Filename order (01-, 02-, …) is the authoring order; `position` is what
  // ReadMe actually sorts by and defaults to that same index when omitted.
  const files = fs
    .readdirSync(PAGES_DIR)
    .filter((f) => f.endsWith('.md'))
    .sort();

  if (files.length === 0) throw new Error(`no .md pages found in ${PAGES_DIR}`);

  const seen = new Set();
  const pages = files.map((file, index) => {
    const raw = fs.readFileSync(path.join(PAGES_DIR, file), 'utf8');
    const { head, body } = splitFrontmatter(raw, file);
    const meta = parseFrontmatter(head, file);

    if (seen.has(meta.slug)) throw new Error(`${file}: duplicate slug "${meta.slug}"`);
    seen.add(meta.slug);

    const position = meta.position ? Number(meta.position) : index + 1;
    if (!Number.isFinite(position)) throw new Error(`${file}: position is not a number`);

    return {
      slug: meta.slug,
      title: meta.title,
      category: meta.category,
      position,
      excerpt: meta.excerpt ?? '',
      body,
      source: `docs/readme-io/pages/${file}`,
    };
  });

  const banner =
    '// GENERATED by scripts/gen-readme-content.mjs — do not edit by hand.\n' +
    '// Edit the markdown under docs/readme-io/pages/ and re-run:\n' +
    '//   npm run gen:readme-content\n\n';

  const types =
    'export interface ReadmePage {\n' +
    '  slug: string;\n' +
    '  title: string;\n' +
    '  category: string;\n' +
    '  position: number;\n' +
    '  excerpt: string;\n' +
    '  body: string;\n' +
    '  source: string;\n' +
    '}\n\n';

  const out =
    banner +
    types +
    `export const PAGES: ReadmePage[] = ${JSON.stringify(pages, null, 2)};\n`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out, 'utf8');

  const rel = path.relative(ROOT, OUT).replace(/\\/g, '/');
  console.log(`gen-readme-content: ${pages.length} page(s) → ${rel}`);
  for (const p of pages) console.log(`  ${String(p.position).padStart(2)}  ${p.slug}  (${p.title})`);
}

main();
